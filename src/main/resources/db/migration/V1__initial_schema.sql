CREATE SEQUENCE users_user_id_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE employees_employee_id_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE clients_client_id_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE offers_offer_id_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE contracts_contract_id_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE designer_commissions_commission_id_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE users (
    user_id INTEGER NOT NULL DEFAULT nextval('users_user_id_seq'),
    username VARCHAR(50) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    email VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_pkey PRIMARY KEY (user_id),
    CONSTRAINT users_username_key UNIQUE (username),
    CONSTRAINT users_email_key UNIQUE (email)
);

CREATE TABLE employees (
    employee_id INTEGER NOT NULL DEFAULT nextval('employees_employee_id_seq'),
    user_id INTEGER NOT NULL,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    phone_number VARCHAR(20) NOT NULL,
    hire_date DATE NOT NULL,
    position VARCHAR(255) NOT NULL,
    CONSTRAINT employees_pkey PRIMARY KEY (employee_id),
    CONSTRAINT employees_user_id_key UNIQUE (user_id),
    CONSTRAINT employees_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE TABLE clients (
    client_id INTEGER NOT NULL DEFAULT nextval('clients_client_id_seq'),
    first_name VARCHAR(50),
    last_name VARCHAR(50),
    company_name VARCHAR(150),
    email VARCHAR(100) NOT NULL,
    phone_number VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT clients_pkey PRIMARY KEY (client_id)
);

CREATE TABLE designers (
    designer_id INTEGER NOT NULL,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    phone_number VARCHAR(20) NOT NULL,
    email VARCHAR(100) NOT NULL,
    CONSTRAINT designers_pkey PRIMARY KEY (designer_id)
);

CREATE TABLE client_addresses (
    address_id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    client_id INTEGER NOT NULL,
    street VARCHAR(100) NOT NULL,
    building_number VARCHAR(10) NOT NULL,
    apartment_number VARCHAR(10),
    postal_code VARCHAR(10) NOT NULL,
    city VARCHAR(100) NOT NULL,
    CONSTRAINT client_addresses_pkey PRIMARY KEY (address_id),
    CONSTRAINT client_addresses_client_id_fkey FOREIGN KEY (client_id) REFERENCES clients (client_id)
);

CREATE TABLE offers (
    offer_id INTEGER NOT NULL DEFAULT nextval('offers_offer_id_seq'),
    client_id INTEGER NOT NULL,
    created_by INTEGER NOT NULL,
    offer_number VARCHAR(50) NOT NULL,
    offer_date DATE NOT NULL,
    valid_until DATE NOT NULL,
    total_amount NUMERIC(12, 2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    description TEXT,
    CONSTRAINT offers_pkey PRIMARY KEY (offer_id),
    CONSTRAINT offers_offer_number_key UNIQUE (offer_number),
    CONSTRAINT offers_client_id_fkey FOREIGN KEY (client_id) REFERENCES clients (client_id),
    CONSTRAINT offers_created_by_fkey FOREIGN KEY (created_by) REFERENCES employees (employee_id)
);

CREATE TABLE projects (
    project_id INTEGER NOT NULL,
    client_id INTEGER NOT NULL,
    offer_id INTEGER,
    project_name VARCHAR(150) NOT NULL,
    description TEXT,
    status VARCHAR(30) NOT NULL,
    start_date DATE,
    end_date DATE,
    installation_street VARCHAR(100) NOT NULL,
    installation_building_number VARCHAR(10) NOT NULL,
    installation_apartment_number VARCHAR(10),
    installation_postal_code VARCHAR(10) NOT NULL,
    installation_city VARCHAR(100) NOT NULL,
    CONSTRAINT projects_pkey PRIMARY KEY (project_id),
    CONSTRAINT projects_client_id_fkey FOREIGN KEY (client_id) REFERENCES clients (client_id),
    CONSTRAINT projects_offer_id_fkey FOREIGN KEY (offer_id) REFERENCES offers (offer_id)
);

CREATE TABLE contracts (
    contract_id INTEGER NOT NULL DEFAULT nextval('contracts_contract_id_seq'),
    project_id INTEGER NOT NULL,
    contract_number VARCHAR(50) NOT NULL,
    signed_date DATE NOT NULL,
    contract_value NUMERIC(12, 2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    document_path VARCHAR(255),
    CONSTRAINT contracts_pkey PRIMARY KEY (contract_id),
    CONSTRAINT contracts_project_id_key UNIQUE (project_id),
    CONSTRAINT contracts_contract_number_key UNIQUE (contract_number),
    CONSTRAINT contracts_project_id_fkey FOREIGN KEY (project_id) REFERENCES projects (project_id)
);

CREATE TABLE project_employees (
    project_id INTEGER NOT NULL,
    employee_id INTEGER NOT NULL,
    CONSTRAINT project_employees_pkey PRIMARY KEY (project_id, employee_id),
    CONSTRAINT project_employees_project_id_fkey FOREIGN KEY (project_id) REFERENCES projects (project_id),
    CONSTRAINT project_employees_employee_id_fkey FOREIGN KEY (employee_id) REFERENCES employees (employee_id)
);

CREATE TABLE tasks (
    task_id INTEGER NOT NULL,
    project_id INTEGER,
    assigned_to INTEGER NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    status VARCHAR(30) NOT NULL,
    priority VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    due_date DATE,
    completed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT tasks_pkey PRIMARY KEY (task_id),
    CONSTRAINT tasks_project_id_fkey FOREIGN KEY (project_id) REFERENCES projects (project_id),
    CONSTRAINT tasks_assigned_to_fkey FOREIGN KEY (assigned_to) REFERENCES employees (employee_id)
);

CREATE TABLE designer_commissions (
    commission_id INTEGER NOT NULL DEFAULT nextval('designer_commissions_commission_id_seq'),
    designer_id INTEGER NOT NULL,
    client_id INTEGER NOT NULL,
    commission_amout NUMERIC(12, 2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT designer_commissions_pkey PRIMARY KEY (commission_id),
    CONSTRAINT uq_designer_client UNIQUE (designer_id, client_id),
    CONSTRAINT designer_commissions_designer_id_fkey FOREIGN KEY (designer_id) REFERENCES designers (designer_id),
    CONSTRAINT designer_commissions_client_id_fkey FOREIGN KEY (client_id) REFERENCES clients (client_id)
);
